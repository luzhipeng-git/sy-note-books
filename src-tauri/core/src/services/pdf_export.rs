//! Native PDF export: convert a single Markdown file to PDF using IronPress.
//!
//! IronPress is a pure-Rust HTML/CSS/Markdown→PDF converter with a built-in
//! layout engine (flexbox, grid, @page, @font-face). Unlike genpdf-chinese
//! (the previous engine — unmaintained, no CSS, manual element rendering),
//! IronPress handles CSS layout natively, producing high-quality output
//! comparable to browser-based rendering.
//!
//! CJK text is shaped via HarfBuzz (rustybuzz) with automatic Unicode font
//! fallback — no manual font registration needed. Images (PNG/JPEG/SVG) are
//! embedded as data URIs in the HTML, which IronPress renders directly.

use std::fs;
use std::path::Path;

use ironpress::{HtmlConverter, Margin, PageSize};

use super::export;

// ═══════════════════════════════════════════════════════════════
// Public API
