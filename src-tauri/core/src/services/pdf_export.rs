/// Export a single Markdown file as a PDF document.
///
/// The Markdown is converted to styled HTML (with embedded images and CSS)
/// via `export::export_pdf_file_html`, then rendered to PDF by IronPress's
/// built-in layout engine.
pub fn export_file_as_pdf(
    workspace_path: &Path,
    file_path: &str,
    output_path: &Path,
    title_override: Option<&str>,
    author_override: Option<&str>,
) -> Result<(), String> {
    // 1. Generate styled HTML with embedded data-URI images
    let html = export::export_pdf_file_html(
        workspace_path,
        file_path,
        title_override,
        author_override,
    )?;

    // 2. Convert HTML → PDF via IronPress
    //
    // IronPress discovers system fonts automatically (fontdb), so CJK text
    // works out-of-the-box on any system with CJK fonts installed. We
    // disable HTML sanitization because the HTML is generated by our own
    // trusted md_to_html pipeline — it contains no <script> or event
    // handlers, and sanitization would strip the <style> block we need.
    let pdf_bytes = HtmlConverter::new()
        .page_size(PageSize::A4)
        .margin(Margin::uniform(56.7)) // ~2cm at 72dpi
        .sanitize(false)
        .convert(&html)
        .map_err(|e| format!("PDF 生成失败：{e}"))?;

    // 3. Write output
    if let Some(parent) = output_path.parent() {
        fs::create_dir_all(parent).map_err(|e| format!("创建输出目录失败：{e}"))?;
    }
    fs::write(output_path, &pdf_bytes)
        .map_err(|e| format!("写入 PDF 失败：{e}"))?;

    Ok(())
}

